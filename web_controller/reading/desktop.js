(() => {
  'use strict';
  const host = window.ICeClassDesktop;
  if (!host) return;
  document.documentElement.dataset.desktop = 'true';
  let leaving = false;
  const isFullscreen = () => host.fullscreen !== false;
  let hold, feedback, hint, hintTimer, suppressClickUntil = 0;
  let exitPending = false;
  const documents = new Map(), wiredFrames = new WeakSet();
  const controls = 'button,a,input,textarea,select,label,summary,[role="button"],[role="slider"],[contenteditable]:not([contenteditable="false"]),video[controls]';

  function cancelHold() {
    if (hold) cancelAnimationFrame(hold.animation);
    hold = undefined;
    if (feedback) feedback.hidden = true;
  }
  function syncPresentation() {
    cancelHold(); exitPending = false;
    const fullscreen = isFullscreen();
    document.documentElement.dataset.desktopFullscreen = String(fullscreen);
    for (const doc of documents.keys()) doc.documentElement.dataset.readingTouchFullscreen = String(fullscreen);
    clearTimeout(hintTimer);
    if (!hint) return;
    hint.hidden = !fullscreen;
    if (fullscreen) hintTimer = setTimeout(() => { hint.hidden = true; }, 6500);
  }
  function startHold(event, doc) {
    if (hold) { cancelHold(); return; }
    if (leaving || exitPending || !isFullscreen() || event.button !== 0 || event.isPrimary === false || event.target.closest?.(controls)) return;
    const current = hold = { doc, id: event.pointerId, x: event.clientX, y: event.clientY, started: performance.now() };
    const tick = now => {
      if (hold !== current) return;
      const elapsed = now - current.started;
      if (elapsed >= 220) {
        feedback.hidden = false;
        feedback.style.setProperty('--hold-progress', Math.min(elapsed / 2000, 1));
        hint.hidden = true;
      }
      if (elapsed >= 2000) {
        suppressClickUntil = performance.now() + 900;
        cancelHold(); exitPending = true;
        host.send('exit-fullscreen');
        return;
      }
      current.animation = requestAnimationFrame(tick);
    };
    current.animation = requestAnimationFrame(tick);
  }
  function pruneDocuments() {
    for (const [doc, record] of documents) {
      if (doc === document) continue;
      const owner = doc.defaultView?.frameElement;
      if (owner?.isConnected && owner.contentDocument === doc) continue;
      if (hold?.doc === doc) cancelHold();
      record.abort.abort(); record.observer.disconnect(); documents.delete(doc);
    }
  }
  function watchFrame(frame, signal) {
    if (wiredFrames.has(frame)) return;
    wiredFrames.add(frame);
    const connect = () => {
      pruneDocuments();
      try { if (frame.contentDocument?.body) bindDocument(frame.contentDocument); } catch { /* Only our same-origin reading frames participate. */ }
    };
    frame.addEventListener('load', connect, { signal }); connect();
  }
  function bindDocument(doc) {
    if (documents.has(doc)) return;
    const abort = new AbortController(), options = { capture: true, signal: abort.signal };
    const observer = new MutationObserver(records => {
      let removed = false;
      for (const record of records) {
        for (const node of record.addedNodes) {
          if (node.nodeType !== 1) continue;
          if (node.tagName === 'IFRAME') watchFrame(node, abort.signal);
          node.querySelectorAll('iframe').forEach(frame => watchFrame(frame, abort.signal));
        }
        removed ||= record.removedNodes.length > 0;
      }
      if (removed) pruneDocuments();
    });
    documents.set(doc, { abort, observer });
    doc.documentElement.dataset.readingTouchFullscreen = String(isFullscreen());
    const style = doc.createElement('style');
    style.textContent = 'html[data-reading-touch-fullscreen="true"] body{user-select:none;-webkit-user-select:none;-webkit-touch-callout:none}input,textarea,[contenteditable="true"]{user-select:text;-webkit-user-select:text}';
    doc.head.append(style);
    doc.addEventListener('pointerdown', event => startHold(event, doc), options);
    doc.addEventListener('pointermove', event => {
      if (hold?.doc === doc && event.pointerId === hold.id && Math.hypot(event.clientX - hold.x, event.clientY - hold.y) > 18) cancelHold();
    }, options);
    doc.addEventListener('pointerup', event => {
      if (hold?.doc === doc && event.pointerId === hold.id) cancelHold();
      // Consume the click generated by this release, then allow the next tap.
      if (suppressClickUntil) setTimeout(() => { suppressClickUntil = 0; }, 0);
    }, options);
    for (const name of ['pointercancel', 'lostpointercapture']) doc.addEventListener(name, event => {
      if (hold?.doc === doc && event.pointerId === hold.id) cancelHold();
    }, options);
    doc.addEventListener('scroll', () => { if (hold?.doc === doc || doc === document) cancelHold(); }, options);
    doc.addEventListener('visibilitychange', () => { if (doc.hidden && (hold?.doc === doc || doc === document)) cancelHold(); }, options);
    doc.addEventListener('contextmenu', event => { if (isFullscreen() || performance.now() < suppressClickUntil) event.preventDefault(); }, options);
    doc.addEventListener('click', event => {
      if (event.detail > 0 && performance.now() < suppressClickUntil) { event.preventDefault(); event.stopImmediatePropagation(); }
    }, options);
    // Focusing an iframe briefly blurs its parent before document.hasFocus()
    // includes the child. Check after that handoff; leaving the app still cancels.
    doc.defaultView.addEventListener('blur', () => { setTimeout(() => { if (!document.hasFocus()) cancelHold(); }, 0); }, { signal: abort.signal });
    observer.observe(doc.body, { childList: true, subtree: true });
    doc.querySelectorAll('iframe').forEach(frame => watchFrame(frame, abort.signal));
  }
  function mount() {
    feedback = document.createElement('div'); feedback.id = 'reading-hold-feedback'; feedback.hidden = true;
    feedback.setAttribute('role', 'status'); feedback.setAttribute('aria-live', 'polite');
    feedback.innerHTML = '<span class="reading-hold-ring" aria-hidden="true"></span><span><strong>继续按住，即可退出全屏</strong><small>松手取消 · 不会结束本次早读</small></span>';
    hint = document.createElement('div'); hint.id = 'reading-touch-hint'; hint.hidden = true;
    hint.innerHTML = '<span aria-hidden="true">◉</span> 长按屏幕空白处 2 秒，退出全屏';
    document.body.append(feedback, hint);
    bindDocument(document); syncPresentation();
  }
  window.addEventListener('iceclass:fullscreenchange', syncPresentation);
  window.addEventListener('pagehide', () => {
    cancelHold(); clearTimeout(hintTimer);
    for (const record of documents.values()) { record.abort.abort(); record.observer.disconnect(); }
    documents.clear();
  });
  document.documentElement.dataset.desktopFullscreen = String(isFullscreen());
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', mount, { once: true }); else mount();
  window.ReadingDesktop = {
    isFullscreen,
    enterFullscreen: () => host.send('enter-fullscreen'),
    exitFullscreen: () => host.send('exit-fullscreen'),
    toggleFullscreen: () => host.send('fullscreen'),
    attachFrameDocument(doc) {
      try {
        const frame = doc.defaultView?.frameElement;
        if (frame?.contentDocument === doc && documents.has(frame.ownerDocument)) bindDocument(doc);
      } catch { /* Do not attach to outside content. */ }
    },
    async prepareToLeave() {
      if (leaving) return;
      leaving = true; cancelHold(); clearTimeout(hintTimer);
      if (hint) hint.hidden = true;
      window.dispatchEvent(new Event('iceclass:leave'));
      await window.ReadingIntegration?.flushNow?.();
    }
  };
})();
